#!/usr/bin/env python3
"""Generates src/catalog.generated.c from the models.dev catalog.

Run `make catalog` to refresh it. The output is committed, so normal builds
need no network.
"""

import json
import sys
import urllib.request

SOURCE = "https://models.dev/api.json"
PROVIDERS = ["opencode", "opencode-go"]


def fetch(src):
    if src.startswith(("http://", "https://")):
        req = urllib.request.Request(src, headers={"User-Agent": "cage-catalog/1"})
        with urllib.request.urlopen(req) as r:
            return json.load(r)
    with open(src) as f:
        return json.load(f)


def cstr(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def effort_of(model):
    for opt in model.get("reasoning_options") or []:
        if opt.get("type") == "effort":
            return opt.get("values") or []
    return None


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else SOURCE
    out = sys.argv[2] if len(sys.argv) > 2 else "src/catalog.generated.c"
    data = fetch(src)

    rows = []
    arrays = {}  # tuple of values -> generated array identifier

    for provider in PROVIDERS:
        p = data.get(provider)
        if not p:
            sys.exit("catalog: provider %r missing from source" % provider)
        for mid in sorted(p["models"]):
            m = p["models"][mid]
            effort = effort_of(m)
            ident, elen = "NULL", 0
            if effort:
                key = tuple(effort)
                if key not in arrays:
                    arrays[key] = "effort_%d" % len(arrays)
                ident, elen = arrays[key], len(effort)
            rows.append((
                provider,
                mid,
                m.get("name") or mid,
                bool(m.get("attachment")),
                int((m.get("limit") or {}).get("context") or 0),
                ident,
                elen,
            ))

    lines = [
        "// Generated by tools/gen_catalog.py from models.dev. Do not edit.",
        "// Refresh with `make catalog`.",
        "",
        '#include "catalog.h"',
        "",
    ]
    for key, ident in arrays.items():
        lines.append("static const char *const %s[] = {%s};" % (
            ident, ", ".join(cstr(v) for v in key)))
    if arrays:
        lines.append("")
    lines.append("const cage_model_info cage_catalog_entries[] = {")
    for provider, mid, name, images, ctx, ident, elen in rows:
        lines.append("    {%s, %s, %s, %s, %dL, %s, %d}," % (
            cstr(provider), cstr(mid), cstr(name),
            "true" if images else "false", ctx, ident, elen))
    lines += [
        "};",
        "",
        "const size_t cage_catalog_entries_len =",
        "    sizeof cage_catalog_entries / sizeof cage_catalog_entries[0];",
        "",
    ]

    with open(out, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d models)" % (out, len(rows)))


if __name__ == "__main__":
    main()
