#!/usr/bin/env python3
"""Generates src/queries.generated.c from the tree-sitter queries in vendor/.

The .scm files under vendor/queries/ are the source of truth. Run
`make queries` after changing one; the output is committed, so normal builds
read no query files from disk.
"""

import os
import sys

DIR = "vendor/queries"
OUT = "src/queries.generated.c"


def cstr(s):
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "?":
            # Escape ? so "??" followed by a trigraph letter cannot be read as
            # a trigraph under strict -std=c11.
            out.append("\\?")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else DIR
    out_path = sys.argv[2] if len(sys.argv) > 2 else OUT

    langs = sorted(
        d for d in os.listdir(base)
        if os.path.isfile(os.path.join(base, d, "highlights.scm"))
    )

    lines = [
        "// Generated by tools/gen_queries.py from vendor/queries. Do not edit.",
        "// Refresh with `make queries`.",
        "",
        '#include "queries.h"',
        "",
        "static const tiny_query tiny_queries[] = {",
    ]
    for lang in langs:
        with open(os.path.join(base, lang, "highlights.scm")) as f:
            body = f.read()
        lines.append("    {%s,\n     %s}," % (cstr(lang), cstr(body)))
    lines += [
        "};",
        "",
        "const char *tiny_query_for(const char *lang) {",
        "    for (size_t i = 0; i < sizeof tiny_queries / sizeof tiny_queries[0]; i++)",
        "        if (strcmp(tiny_queries[i].lang, lang) == 0) return tiny_queries[i].text;",
        "    return NULL;",
        "}",
        "",
    ]

    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s (%d languages: %s)" % (out_path, len(langs), " ".join(langs)))


if __name__ == "__main__":
    main()
